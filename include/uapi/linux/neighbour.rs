pub const NUD_INCOMPLETE: c_uint = 0x01;
pub const NUD_REACHABLE: c_uint = 0x02;
pub const NUD_STALE: c_uint = 0x04;
pub const NUD_DELAY: c_uint = 0x08;
pub const NUD_PROBE: c_uint = 0x10;
pub const NUD_FAILED: c_uint = 0x20;
// Dummy states
pub const NUD_NOARP: c_uint = 0x40;
pub const NUD_PERMANENT: c_uint = 0x80;
pub const NUD_NONE: c_uint = 0x00;
// NUD_NOARP & NUD_PERMANENT are pseudostates, they never change and make no
// address resolution or NUD.
//
// NUD_PERMANENT also cannot be deleted by garbage collectors. This holds true
// for dynamic entries with NTF_EXT_LEARNED flag as well. However, upon carrier
// down event, NUD_PERMANENT entries are not flushed whereas NTF_EXT_LEARNED
// flagged entries explicitly are (which is also consistent with the routing
// subsystem).
//
// When NTF_EXT_LEARNED is set for a bridge fdb entry the different cache entry
// states don't make sense and thus are ignored. Such entries don't age and
// can roam.
//
// NTF_EXT_MANAGED flagged neigbor entries are managed by the kernel on behalf
// of a user space control plane, and automatically refreshed so that (if
// possible) they remain in NUD_REACHABLE state.
//
// NTF_EXT_LOCKED flagged bridge FDB entries are entries generated by the
// bridge in response to a host trying to communicate via a locked bridge port
// with MAB enabled. Their purpose is to notify user space that a host requires
// authentication.
//
// NTF_EXT_EXT_VALIDATED flagged neighbor entries were externally validated by
// a user space control plane. The kernel will not remove or invalidate them,
// but it can probe them and notify user space when they become reachable.
//
#[repr(C)]
#[derive(Copy, Clone)]
pub struct nda_cacheinfo {
    pub ndm_confirmed: __u32,
    pub ndm_used: __u32,
    pub ndm_updated: __u32,
    pub ndm_refcnt: __u32,
}

//
// Neighbour tables specific messages.
//
// To retrieve the neighbour tables send RTM_GETNEIGHTBL with the
// NLM_F_DUMP flag set. Every neighbour table configuration is
// spread over multiple messages to avoid running into message
// size limits on systems with many interfaces. The first message
// in the sequence transports all not device specific data such as
// statistics, configuration, and the default parameter set.
// This message is followed by 0..n messages carrying device
// specific parameter sets.
// Although the ordering should be sufficient, NDTA_NAME can be
// used to identify sequences. The initial message can be identified
// by checking for NDTA_CONFIG. The device specific messages do
// not contain this TLV but have NDTPA_IFINDEX set to the
// corresponding interface index.
//
// To change neighbour table attributes, send RTM_SETNEIGHTBL
// with NDTA_NAME set. Changeable attribute include NDTA_THRESH[1-3],
// NDTA_GC_INTERVAL, and all TLVs in NDTA_PARMS unless marked
// otherwise. Device specific parameter sets can be changed by
// setting NDTPA_IFINDEX to the interface index of the corresponding
// device.
//
